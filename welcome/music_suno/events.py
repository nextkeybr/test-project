"""Extract kick / snare / hat onsets (+ loudness) from the fitted track for audio-reactive motion.

usage: python events.py music.wav audio_events.js
writes: const AUDIO = { kick:[[t,s],...], snare:[...], hat:[...], rms:[...per 1/60s...] }
"""
import json
import sys
import wave

import numpy as np
from scipy.signal import butter, sosfilt

w = wave.open(sys.argv[1]); sr = w.getframerate()
x = np.frombuffer(w.readframes(w.getnframes()), '<i2').reshape(-1, 2).mean(1) / 32768
HOP = sr // 200                                     # 5 ms frames
fps = sr / HOP


def band_env(lo, hi):
    y = sosfilt(butter(4, [lo, hi] if hi else lo, 'band' if hi else 'high', fs=sr, output='sos'), x)
    n = len(y) // HOP
    return np.sqrt(np.add.reduceat(y[:n * HOP] ** 2, np.arange(0, n * HOP, HOP)) / HOP)


def onsets(env, min_gap, k=1.6):
    le = np.log(env + 1e-5)
    flux = np.maximum(0, np.diff(le, prepend=le[0]))
    win = int(0.5 * fps)
    loc = np.convolve(flux, np.ones(win) / win, 'same')
    thr = loc * k + 0.02
    out, last = [], -1e9
    for i in range(2, len(flux) - 2):
        if flux[i] > thr[i] and flux[i] == flux[i - 2:i + 3].max() and (i - last) / fps >= min_gap:
            out.append((i / fps, flux[i] * env[min(len(env) - 1, i + 2)]))
            last = i
    if not out:
        return []
    s = np.array([v for _, v in out]); s = s / np.percentile(s, 95)
    return [[round(t, 3), round(float(min(1.0, v)), 3)] for (t, _), v in zip(out, s) if v > 0.12]


ev = {
    'kick': onsets(band_env(40, 110), 0.18),
    'snare': onsets(band_env(1500, 5000), 0.15),
    'hat': onsets(band_env(9000, None), 0.08),
}
n = len(x) // (sr // 60)
r = np.sqrt(np.add.reduceat(x[:n * (sr // 60)] ** 2, np.arange(0, n * (sr // 60), sr // 60)) / (sr // 60))
ev['rms'] = [round(float(v), 3) for v in r / r.max()]
with open(sys.argv[2], 'w') as f:
    f.write('// generated by music_suno/events.py from the fitted soundtrack\nconst AUDIO = ' + json.dumps(ev) + ';\n')
for k in ('kick', 'snare', 'hat'):
    print(k, len(ev[k]), ev[k][:6])
